#!/usr/bin/env bash
# Oracle check 5: installs.
#   tools/oracle/check-install.sh                # the golden tests (archives built in the test)
#   tools/oracle/check-install.sh <instance>     # + replay the instance's downloads
#
# With an instance (read only): its downloads are reflink-copied into a scratch instance in
# _stage/oracle/install/<name>/ (empty mods, same ModOrganizer.ini), each archive is installed
# with `strata install --merge` (a later archive merged into an earlier mod, as the user did),
# and every mod the instance itself installed from that archive (its
# meta.ini installationFile) must have the same files (meta.ini aside). Archives no mod names
# are installed but not compared. Exits non-zero on any difference.
set -euo pipefail
here="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$here"

cargo test -q -p strata-install --test golden > _stage/check-install-golden.log 2>&1 || {
  echo "check 5 FAILED: golden tests, see _stage/check-install-golden.log"; exit 1; }
echo "check 5 golden ok: $(grep -o '[0-9]* passed' _stage/check-install-golden.log | tail -1)"

[ $# -ge 1 ] || exit 0
instance="$(cd "$1" && pwd)"
strata="${STRATA:-$here/target/release/strata-headless}"
[ -x "$strata" ] || { echo "build first: cargo build --release -p strata-cli"; exit 2; }

name="$(basename "$instance" | tr ' /' '__')"
out="$here/_stage/oracle/install/$name"
rm -rf "$out"
mkdir -p "$out/mods" "$out/downloads"
cp "$instance/ModOrganizer.ini" "$out/"
for f in categories.dat nexuscatmap.dat; do [ -f "$instance/$f" ] && cp "$instance/$f" "$out/"; done
profile="$(sed -n 's/^selected_profile=\(@ByteArray(\)\{0,1\}\([^)]*\))\{0,1\}$/\2/p' "$instance/ModOrganizer.ini" | head -1)"
mkdir -p "$out/profiles/$profile"
printf '# This file was automatically generated by Mod Organizer.\r\n' > "$out/profiles/$profile/modlist.txt"
cp --reflink=auto -a "$instance/downloads/." "$out/downloads/"

fail=0; compared=0
shopt -s nullglob
for archive in "$out"/downloads/*.{7z,zip,rar,7Z,ZIP,RAR}; do
  base="$(basename "$archive")"
  # the mod(s) of the real instance installed from this archive
  mapfile -t real < <(python3 - "$instance/mods" "$base" <<'PY'
import os, sys
mods, base = sys.argv[1], sys.argv[2]
for m in sorted(os.listdir(mods)):
    try:
        lines = open(os.path.join(mods, m, "meta.ini"), encoding="utf-8", errors="replace").read().splitlines()
    except OSError:
        continue
    if "installationFile=" + base in (l.rstrip("\r") for l in lines):
        print(os.path.join(mods, m))
PY
)
  log="$out/$(echo "$base" | tr ' /' '__').log"
  if ! "$strata" install -i "$out" --json --merge "$archive" > "$log" 2>&1; then
    echo "  install failed: $base ($(tail -1 "$log"))"
    [ ${#real[@]} -eq 0 ] || fail=1
    continue
  fi
  mod="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["installed"]["name"])' "$log")"
  [ ${#real[@]} -ne 0 ] || { echo "  installed (no mod to compare): $base -> $mod"; continue; }
  for r in "${real[@]}"; do
    compared=$((compared + 1))
    a="$(cd "$r" && find . -mindepth 1 -not -name meta.ini | LC_ALL=C sort)"
    b="$(cd "$out/mods/$mod" && find . -mindepth 1 -not -name meta.ini | LC_ALL=C sort)"
    if [ "$a" = "$b" ] && [ "$(basename "$r")" = "$mod" ]; then
      echo "  same: $mod ($(echo "$b" | wc -l) entries)"
    else
      fail=1
      echo "  DIFFERENT: $base -> Strata '$mod', instance '$(basename "$r")'"
      diff <(echo "$a") <(echo "$b") | head -5 | sed 's/^/    /'
    fi
  done
done

if [ $fail -eq 0 ]; then
  echo "check 5 ok: $compared mods compared, $instance"
else
  echo "check 5 FAILED on $instance (scratch instance: $out)"
  exit 1
fi
