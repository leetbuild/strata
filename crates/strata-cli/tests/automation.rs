#[test]
fn vfs_export_writes_every_file() {
    let (_d, root) = instance();
    let out = root.join("vfs.csv");
    strata(&root, &["vfs-export", out.to_str().unwrap()]);
    let text = fs::read_to_string(&out).unwrap();
    let lines: Vec<_> = text.lines().collect();
    assert_eq!(lines[0], "path,origin,real");
    assert!(lines.iter().any(|l| l.starts_with("Data/textures/x.dds,B,")));
    assert!(lines.iter().any(|l| l.starts_with("enbseries.ini,B,")), "Root files at the game folder");
}

