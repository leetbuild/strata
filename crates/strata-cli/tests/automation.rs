#[test]
fn crash_logs_are_listed_and_labelled() {
    let (d, root) = instance();
    let prefix = d.path().join("prefix");
    let mut ini = fs::read_to_string(root.join("ModOrganizer.ini")).unwrap();
    ini.push_str(&format!("[fluorine]\r\nprefix_path={}\r\n", prefix.display()));
    fs::write(root.join("ModOrganizer.ini"), ini).unwrap();
    let logs = prefix.join("pfx/drive_c/users/steamuser/Documents/My Games/Skyrim Special Edition/SKSE");
    let log = "Skyrim SSE v1.6.1170\r\nCALL STACK ([P]robable / [S]tack scan):\r\n\
               \t[ 0][P] 0x0001405B35C7 SkyrimSE.exe+05B35C7 -> 36564+0x5D7\ttest dil, dil\r\n\r\nREGISTERS:\r\n";
    put(&logs.join("crash-2026-11-26-10-00-00.log"), log.as_bytes());
    put(&logs.join("crash-2026-11-25-10-00-00.log"), log.replace("v1.6.1170", "v1.5.97").as_bytes());
    let db = d.path().join("skyrimae.rename");
    put(&db, b"1\n36564 Main::Update_*\n");
    let run = |args: &[&str]| {
        let out = Command::new(env!("CARGO_BIN_EXE_strata-headless"))
            .arg("-i")
            .arg(&root)
            .arg("--json")
            .args(args)
            .env("XDG_RUNTIME_DIR", root.join("run"))
            .env("XDG_DATA_HOME", d.path().join("data"))
            .env("STRATA_CRASHLOG_DATABASE", &db)
            .stdin(Stdio::null())
            .output()
            .unwrap();
        assert!(out.status.success(), "{}", String::from_utf8_lossy(&out.stderr));
        serde_json::from_slice::<Value>(&out.stdout).unwrap()
    };
    let v = run(&["crashlogs", "list"]);
    assert_eq!(v["logs"].as_array().unwrap().len(), 2);
    assert!(v["logs"][0].as_str().unwrap().ends_with("crash-2026-11-26-10-00-00.log"));
    let v = run(&["crashlogs", "label"]);
    assert_eq!(v["logs"][0]["outcome"], "labelled 1 frame(s)");
    assert!(v["logs"][1]["outcome"].as_str().unwrap().starts_with("Skyrim 1.5.97"));
    let labelled = fs::read_to_string(logs.join("crash-2026-11-26-10-00-00.log")).unwrap();
    assert!(labelled.contains("-> 36564+0x5D7 Main::Update\ttest dil, dil\r\n"), "{labelled}");
    assert!(d.path().join("data/Trash/files/crash-2026-11-26-10-00-00.log").is_file());
}

