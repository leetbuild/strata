#[test]
fn toggles_and_priorities_change_the_list() {
    let (_d, root) = instance();
    strata(&root, &["enable", "C"]);
    strata(&root, &["disable", "B"]);
    let list = fs::read_to_string(root.join("profiles/Default/modlist.txt")).unwrap();
    assert!(list.contains("+C") && list.contains("-B"), "{list}");
    strata(&root, &["move", "A", "--to", "3"]);
    let v = strata(&root, &["list"]);
    let a = v["mods"].as_array().unwrap().iter().find(|m| m["name"] == "A").unwrap().clone();
    assert_eq!(a["priority"], 3);
    strata(&root, &["mod", "rename", "C", "See"]);
    assert!(root.join("mods/See").is_dir());
    strata(&root, &["mod", "remove", "See", "--permanent"]);
    assert!(!root.join("mods/See").exists());
}

#[test]
