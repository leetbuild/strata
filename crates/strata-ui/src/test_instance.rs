//! A small instance on disk for tests: `ModOrganizer.ini`, a Game Root, one profile and the
//! mod folders its `modlist.txt` names.

use std::path::{Path, PathBuf};

use strata_core::{Instance, Profile};

pub struct TestInstance {
    _dir: tempfile::TempDir,
    pub root: PathBuf,
}

impl TestInstance {
    /// `modlist` as MO2 writes it (highest priority first); every name gets a folder.
    pub fn new(modlist: &str) -> Self {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path().join("inst");
        let game = root.join("Game Root");
        std::fs::create_dir_all(game.join("Data")).unwrap();
        let wine = format!("Z:{}", game.display()).replace('/', "\\\\");
        std::fs::write(
            root.join("ModOrganizer.ini"),
            format!(
                "[General]\r\ngameName=Skyrim Special Edition\r\nselected_profile=@ByteArray(Default)\r\ngamePath=@ByteArray({wine})\r\n"
            ),
        )
        .unwrap();
        std::fs::write(root.join("categories.dat"), "1|Skyrim Special Edition|0\n2|Buildings|0\n").unwrap();
        let profile = root.join("profiles/Default");
        std::fs::create_dir_all(&profile).unwrap();
        std::fs::write(profile.join("modlist.txt"), format!("# This file was automatically generated by Mod Organizer.\r\n{modlist}")).unwrap();
        std::fs::create_dir_all(root.join("overwrite")).unwrap();
        let t = Self { _dir: dir, root };
        for line in modlist.lines() {
            let name = line.trim().trim_start_matches(['+', '-']);
            if !name.is_empty() && !line.starts_with('*') {
                t.folder(name);
            }
        }
        t
    }

    pub fn folder(&self, name: &str) -> PathBuf {
        let dir = self.root.join("mods").join(name);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    pub fn meta(&self, name: &str, text: &str) {
        std::fs::write(self.folder(name).join("meta.ini"), text).unwrap();
    }

    pub fn path(&self, rel: &str) -> PathBuf {
        self.root.join(rel)
    }

    pub fn open(&self) -> (Instance, Profile) {
        let instance = Instance::open(Path::new(&self.root)).unwrap();
        let profile = instance.profile(None).unwrap();
        (instance, profile)
    }
}
