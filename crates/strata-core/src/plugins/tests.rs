#[test]
fn light_plugins_get_fe_indexes() {
    let f = fixture(&[BASE[0], ("a.esl", 0, &[]), ("b.esp", FLAG_LIGHT, &[]), ("c.esp", 0, &[]), ("d.esp", 0, &[])]);
    let list = PluginList::load(
        f.available.clone(),
        rules(),
        &files(Some("*a.esl\r\n*b.esp\r\nc.esp\r\n*d.esp\r\n"), Some("Skyrim.esm\r\na.esl\r\nb.esp\r\nc.esp\r\nd.esp\r\n"), None),
    );
    let idx: Vec<_> = list.plugins().map(|p| p.index.as_str()).collect();
    assert_eq!(idx, ["00", "FE:000", "FE:001", "", "01"]);
    // An .esl counts as a master for ordering; a light-flagged .esp does not.
    assert!(list.get("a.esl").unwrap().is_master_like());
    assert!(!list.get("b.esp").unwrap().is_master_like());
}

#[test]
fn moves_follow_mo2s_rules() {
    let f = fixture(&[BASE[0], ("M.esm", FLAG_MASTER, &[]), ("a.esp", 0, &["M.esm"]), ("b.esp", 0, &[]), ("c.esp", 0, &[])]);
    let lo = "Skyrim.esm\r\nM.esm\r\na.esp\r\nb.esp\r\nc.esp\r\n";
    let all = "*M.esm\r\n*a.esp\r\n*b.esp\r\n*c.esp\r\n";
    let fresh = || PluginList::load(f.available.clone(), rules(), &files(Some(all), Some(lo), None));

    let mut list = fresh();
    list.send_to_priority(&["c.esp".into()], 0).unwrap();
    assert_eq!(order(&list), ["+Skyrim.esm", "+M.esm", "+c.esp", "+a.esp", "+b.esp"], "an esp stays below the masters");

    let mut list = fresh();
    list.send_to_priority(&["M.esm".into()], usize::MAX).unwrap();
    assert_eq!(order(&list), ["+Skyrim.esm", "+M.esm", "+a.esp", "+b.esp", "+c.esp"], "a master stays above plugins");

    let mut list = fresh();
    list.send_to_priority(&["Skyrim.esm".into()], 3).unwrap();
    assert_eq!(order(&list)[0], "+Skyrim.esm", "primary plugins don't move");

    let mut list = fresh();
    list.send_to_priority(&["b.esp".into(), "c.esp".into()], 2).unwrap();
    assert_eq!(order(&list), ["+Skyrim.esm", "+M.esm", "+b.esp", "+c.esp", "+a.esp"]);

    let mut list = fresh();
    list.send_to_priority(&["a.esp".into()], usize::MAX).unwrap();
    assert_eq!(order(&list), ["+Skyrim.esm", "+M.esm", "+b.esp", "+c.esp", "+a.esp"]);

    assert!(matches!(list.send_to_priority(&["nope.esp".into()], 1), Err(Error::NoSuchPlugin { .. })));
}

#[test]
fn locked_plugins_keep_their_load_order_position() {
    let f = fixture(&[BASE[0], ("a.esp", 0, &[]), ("b.esp", 0, &[]), ("c.esp", 0, &[])]);
    let lo = "Skyrim.esm\r\na.esp\r\nb.esp\r\nc.esp\r\n";
    let all = "*a.esp\r\n*b.esp\r\n*c.esp\r\n";
    // c.esp locked at load order 1: it is pulled up on load.
    let mut list = PluginList::load(f.available.clone(), rules(), &files(Some(all), Some(lo), Some("c.esp|1\r\n")));
    assert_eq!(order(&list), ["+Skyrim.esm", "+c.esp", "+a.esp", "+b.esp"]);
    assert_eq!(list.locked_position("C.ESP"), Some(1));
    // Moving another plugin above it puts it back.
    list.send_to_priority(&["b.esp".into()], 1).unwrap();
    assert_eq!(order(&list), ["+Skyrim.esm", "+c.esp", "+b.esp", "+a.esp"]);
    list.set_locked("c.esp", false).unwrap();
    list.set_locked("a.esp", true).unwrap();
    assert_eq!(list.lockedorder_txt(), format!("{H}a.esp|3\r\n").into_bytes());
    assert!(list.set_locked("skyrim.esm", true).is_ok());
    assert_eq!(list.locked_position("skyrim.esm"), None, "forced plugins are never locked");
}

#[test]
fn enabling_leaves_forced_plugins_alone() {
    let f = fixture(&[BASE[0], ("a.esp", 0, &[])]);
    let mut list = PluginList::load(f.available.clone(), rules(), &files(Some("a.esp\r\n"), Some("Skyrim.esm\r\na.esp\r\n"), None));
    let changed = list.set_enabled(&["a.esp".into(), "skyrim.esm".into()], true).unwrap();
    assert_eq!(changed, ["a.esp"]);
    assert_eq!(list.set_enabled(&["Skyrim.esm".into()], false).unwrap(), Vec::<String>::new());
    assert_eq!(list.get("a.esp").unwrap().load_order, Some(1));
}

#[test]
fn enable_all_and_disable_all_leave_forced_plugins_alone() {
    let f = fixture(&[BASE[0], ("a.esp", 0, &[]), ("b.esp", 0, &[])]);
    let mut list =
        PluginList::load(f.available.clone(), rules(), &files(Some("*a.esp\r\n"), Some("Skyrim.esm\r\na.esp\r\nb.esp\r\n"), None));
    assert_eq!(list.set_enabled_all(false), ["a.esp"]);
    assert_eq!(order(&list), ["+Skyrim.esm", "-a.esp", "-b.esp"], "the primary plugin stays enabled");
    let mut changed = list.set_enabled_all(true);
    changed.sort();
    assert_eq!(changed, ["a.esp", "b.esp"]);
    assert_eq!(order(&list), ["+Skyrim.esm", "+a.esp", "+b.esp"]);
    assert_eq!(list.get("b.esp").unwrap().load_order, Some(2));
    assert!(list.set_enabled_all(true).is_empty());
}

#[test]
fn files_written_by_mo2_are_written_back_the_same() {
    let f = fixture(&[BASE[0], BASE[1], ("M.esm", FLAG_MASTER, &[]), ("a.esp", 0, &[]), ("b.esl", 0, &[])]);
    let plugins = "*M.esm\r\nb.esl\r\n*a.esp\r\n";
    let lo = "Skyrim.esm\r\nUpdate.esm\r\nM.esm\r\nb.esl\r\na.esp\r\n";
    let list = PluginList::load(f.available.clone(), rules(), &files(Some(plugins), Some(lo), Some("")));
    assert_eq!(list.plugins_txt(), format!("{H}{plugins}").into_bytes());
    assert_eq!(list.loadorder_txt().unwrap(), format!("{H}{lo}").into_bytes());
    assert_eq!(list.lockedorder_txt(), H.as_bytes());

    let dir = tempfile::tempdir().unwrap();
    assert_eq!(list.save(dir.path()).unwrap().len(), 3);
    assert!(list.save(dir.path()).unwrap().is_empty(), "nothing changed, nothing written");
}

