use strata_game::plugin::{FLAG_LIGHT, FLAG_MASTER, build_plugin};

use super::*;

const H: &str = "# This file was automatically generated by Mod Organizer.\r\n";

/// A plugin to create: name, flags, masters.
type Spec<'a> = (&'a str, u32, &'a [&'a str]);

struct Fixture {
    _dir: tempfile::TempDir,
    available: Vec<AvailablePlugin>,
}

fn fixture(specs: &[Spec]) -> Fixture {
    let dir = tempfile::tempdir().unwrap();
    let available = specs
        .iter()
        .map(|(name, flags, masters)| {
            let path = dir.path().join(name);
            std::fs::write(&path, build_plugin(*flags, 44, masters, "t", 1)).unwrap();
            AvailablePlugin { name: (*name).into(), origin: "mod".into(), path }
        })
        .collect();
    Fixture { _dir: dir, available }
}

fn rules() -> PluginRules {
    PluginRules {
        primary: ["skyrim.esm", "update.esm", "dawnguard.esm"].map(String::from).to_vec(),
        force_enable_core_files: true,
        light_plugins_supported: true,
        format: strata_game::PluginListFormat::Creation,
    }
}

fn files(plugins: Option<&str>, loadorder: Option<&str>, locked: Option<&str>) -> PluginFiles {
    let b = |s: Option<&str>| s.map(|s| format!("{H}{s}").into_bytes());
    PluginFiles { plugins_txt: b(plugins), loadorder_txt: b(loadorder), lockedorder_txt: b(locked) }
}

fn order(list: &PluginList) -> Vec<String> {
    list.plugins().map(|p| format!("{}{}", if p.enabled { "+" } else { "-" }, p.name)).collect()
}

const BASE: [Spec; 2] = [("Skyrim.esm", FLAG_MASTER, &[]), ("Update.esm", FLAG_MASTER, &["Skyrim.esm"])];

#[test]
fn order_comes_from_loadorder_and_states_from_plugins_txt() {
    let f = fixture(&[BASE[0], BASE[1], ("A.esp", 0, &["Skyrim.esm"]), ("B.esp", 0, &[]), ("M.esm", FLAG_MASTER, &[])]);
    let list = PluginList::load(
        f.available.clone(),
        rules(),
        &files(Some("*M.esm\r\nB.esp\r\n*A.esp\r\n"), Some("Skyrim.esm\r\nUpdate.esm\r\nM.esm\r\nB.esp\r\nA.esp\r\n"), None),
    );
    assert_eq!(order(&list), ["+Skyrim.esm", "+Update.esm", "+M.esm", "-B.esp", "+A.esp"]);
    let a = list.get("a.ESP").unwrap();
    assert_eq!((a.priority, a.load_order, a.index.as_str()), (4, Some(3), "03"));
    assert!(list.get("Skyrim.esm").unwrap().force_loaded);
}

