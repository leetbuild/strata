/// After any sequence of changes, reading back the files the list writes gives the same list
/// (order, states, locks): what Strata shows is what MO2 will read.
#[test]
fn random_changes_survive_a_write_and_a_read() {
    let f = fixture(&[
        BASE[0],
        BASE[1],
        ("M1.esm", FLAG_MASTER, &["Skyrim.esm"]),
        ("M2.esm", FLAG_MASTER, &["M1.esm"]),
        ("L.esl", 0, &[]),
        ("lf.esp", FLAG_LIGHT, &[]),
        ("mf.esp", FLAG_MASTER, &[]),
        ("a.esp", 0, &["M2.esm"]),
        ("b.esp", 0, &["a.esp"]),
        ("c.esp", 0, &[]),
        ("d.esp", 0, &["Gone.esm"]),
        ("e.esp", 0, &[]),
    ]);
    let names: Vec<String> = f.available.iter().map(|a| a.name.clone()).collect();
    let mut seed: u64 = 0x5eed;
    let mut next = |n: usize| {
        seed = seed.wrapping_mul(6_364_136_223_846_793_005).wrapping_add(1_442_695_040_888_963_407);
        ((seed >> 33) as usize) % n
    };
    let snapshot = |l: &PluginList| -> Vec<(String, bool, Option<i64>)> {
        l.plugins().map(|p| (p.name.clone(), p.enabled, l.locked_position(&p.name))).collect()
    };
    for round in 0..400 {
        let mut r = rules();
        if round % 2 == 1 {
            r.format = strata_game::PluginListFormat::Gamebryo;
            r.light_plugins_supported = false;
        }
        let mut list = PluginList::load(f.available.clone(), r.clone(), &PluginFiles::default());
        for _ in 0..8 {
            let name = names[next(names.len())].clone();
            match next(4) {
                0 => drop(list.set_enabled(&[name], true).unwrap()),
                1 => drop(list.set_enabled(&[name], false).unwrap()),
                2 => list.send_to_priority(&[name], next(names.len() + 1)).unwrap(),
                _ => list.set_locked(&name, next(3) == 0).unwrap(),
            }
            let files = PluginFiles {
                plugins_txt: Some(list.plugins_txt()),
                loadorder_txt: list.loadorder_txt(),
                lockedorder_txt: Some(list.lockedorder_txt()),
            };
            let reread = PluginList::load(f.available.clone(), r.clone(), &files);
            // A disabled plugin locked at -1 is dropped on reading (MO2 rejects negative
            // positions), so compare locks only where the position is valid.
            let clean = |s: Vec<(String, bool, Option<i64>)>| -> Vec<_> {
                s.into_iter().map(|(n, e, l)| (n, e, l.filter(|p| *p >= 0))).collect()
            };
            assert_eq!(clean(snapshot(&reread)), clean(snapshot(&list)), "round {round}");
            list = reread;
        }
    }
}

/// Skyrim LE: `plugins.txt` holds only the active plugins (primary ones too), no marks;
/// the order comes from `loadorder.txt`; `.esl` files can never be enabled.
#[test]
fn gamebryo_lists_read_and_write_as_skyrim_le_does() {
    let f = fixture(&[BASE[0], BASE[1], ("M.esm", FLAG_MASTER, &[]), ("a.esp", 0, &[]), ("b.esp", 0, &[]), ("c.esl", 0, &[])]);
    let mut r = rules();
    r.primary = vec!["skyrim.esm".into(), "update.esm".into()];
    r.light_plugins_supported = false;
    r.format = strata_game::PluginListFormat::Gamebryo;
    let plugins = "Skyrim.esm\r\nUpdate.esm\r\nM.esm\r\nb.esp\r\nc.esl\r\n";
    // (an .esl counts as a master for the order even here, as in MO2)
    let lo = "Skyrim.esm\r\nUpdate.esm\r\nM.esm\r\nc.esl\r\na.esp\r\nb.esp\r\n";
    let list = PluginList::load(f.available.clone(), r.clone(), &files(Some(plugins), Some(lo), None));
    assert_eq!(order(&list), ["+Skyrim.esm", "+Update.esm", "+M.esm", "-c.esl", "-a.esp", "+b.esp"]);
    assert!(list.get("c.esl").unwrap().force_disabled);
    assert_eq!(list.plugins_txt(), format!("{H}Skyrim.esm\r\nUpdate.esm\r\nM.esm\r\nb.esp\r\n").into_bytes());
    assert_eq!(list.loadorder_txt().unwrap(), format!("{H}{lo}").into_bytes());
    // A `*` is part of the name for LE: no such plugin, so it stays off.
    let list = PluginList::load(f.available.clone(), r, &files(Some("*a.esp\r\n"), Some(lo), None));
    assert!(!list.get("a.esp").unwrap().enabled);
}
