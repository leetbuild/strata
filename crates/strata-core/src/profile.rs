//! A profile folder: `modlist.txt`, `plugins.txt`, `settings.ini`, local inis and saves.

use std::path::{Path, PathBuf};

use strata_ini::Document;

use crate::{Error, Result};

/// The first line MO2 writes to `modlist.txt` (and to `plugins.txt`).
pub const MODLIST_HEADER: &str = "# This file was automatically generated by Mod Organizer.";

/// How a mod is marked in `modlist.txt`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ListedState {
    /// `+Name`
    Enabled,
    /// `-Name`
    Disabled,
    /// `*Name`: not managed by MO2 (the game's DLC and Creation Club files).
    Foreign,
}

/// One line of `modlist.txt`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ListedMod {
    pub name: String,
    pub state: ListedState,
}

/// `modlist.txt`: the mods in file order, which is **highest priority first**.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct ModListFile {
    pub mods: Vec<ListedMod>,
}

impl ModListFile {
    /// Reads the file as MO2 does (`Profile::refreshModStatus`): blank lines and `#` lines
    /// are skipped, a line without a marker counts as enabled, and a name seen before is
    /// ignored.
    pub fn parse(data: &[u8]) -> Self {
        let mut mods: Vec<ListedMod> = Vec::new();
        for line in data.split(|b| *b == b'\n') {
            let line = line.trim_ascii();
            let (state, name) = match line.first() {
                None | Some(b'#') => continue,
                Some(b'-') => (ListedState::Disabled, &line[1..]),
                Some(b'+') => (ListedState::Enabled, &line[1..]),
                Some(b'*') => (ListedState::Foreign, &line[1..]),
                Some(_) => (ListedState::Enabled, line),
            };
            let name = String::from_utf8_lossy(name.trim_ascii()).into_owned();
            if name.is_empty() || mods.iter().any(|m| m.name == name) {
                continue;
            }
            mods.push(ListedMod { name, state });
        }
        Self { mods }
    }

    /// Writes the file as MO2 does (`Profile::doWriteModlist`): the header, then one line
    /// per mod, CRLF line ends.
    pub fn to_bytes(&self) -> Vec<u8> {
        let mut out = format!("{MODLIST_HEADER}\r\n").into_bytes();
        for listed in &self.mods {
            out.push(match listed.state {
                ListedState::Enabled => b'+',
                ListedState::Disabled => b'-',
                ListedState::Foreign => b'*',
            });
            out.extend_from_slice(listed.name.as_bytes());
            out.extend_from_slice(b"\r\n");
        }
        out
    }
}

/// An opened profile.
#[derive(Debug, Clone)]
pub struct Profile {
    pub name: String,
    pub dir: PathBuf,
    pub modlist: ModListFile,
    /// `settings.ini` `LocalSaves`: saves live in the profile's `saves/`.
    pub local_saves: bool,
    /// `settings.ini` `LocalSettings`: the game's inis live in the profile.
    pub local_settings: bool,
}

impl Profile {
    pub(crate) fn open(name: &str, dir: &Path) -> Result<Self> {
        let modlist_path = dir.join("modlist.txt");
        let data = std::fs::read(&modlist_path).map_err(|source| Error::Read { path: modlist_path, source })?;
        // settings.ini may be absent in a fresh profile: MO2's defaults are false.
        let settings = std::fs::read(dir.join("settings.ini")).map(|d| Document::parse(&d)).unwrap_or_default();
        let flag = |key| settings.value("", key).is_some_and(|v| v.to_bool());
        Ok(Self {
            name: name.to_owned(),
            dir: dir.to_owned(),
            modlist: ModListFile::parse(&data),
            local_saves: flag("LocalSaves"),
            local_settings: flag("LocalSettings"),
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const FILE: &[u8] = b"# This file was automatically generated by Mod Organizer.\r\n+Top\r\n-Off\r\n*DLC: Dawnguard\r\n+Tools_separator\r\n";

    #[test]
    fn a_file_written_by_mo2_round_trips() {
        let list = ModListFile::parse(FILE);
        assert_eq!(list.mods.len(), 4);
        assert_eq!(list.mods[0], ListedMod { name: "Top".into(), state: ListedState::Enabled });
        assert_eq!(list.mods[2].state, ListedState::Foreign);
        assert_eq!(list.to_bytes(), FILE);
    }

    #[test]
    fn odd_lines_are_read_as_mo2_reads_them() {
        let list = ModListFile::parse(b"\n  +Spaced  \nBare\n+Dup\n-Dup\n#+Comment\n+\n");
        let names: Vec<_> = list.mods.iter().map(|m| (m.name.as_str(), m.state)).collect();
        assert_eq!(
            names,
            [("Spaced", ListedState::Enabled), ("Bare", ListedState::Enabled), ("Dup", ListedState::Enabled)]
        );
    }
}

/// `plugins.txt` or `loadorder.txt`: plugin names in load order.
///
/// For Skyrim SE, `plugins.txt` marks active plugins with `*` and leaves the game's primary
/// plugins out; `loadorder.txt` (MO2's own file) lists every plugin, without marks.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct PluginListFile {
    /// `(name, active)`. `active` is always false for a file without `*` marks.
    pub plugins: Vec<(String, bool)>,
}

impl PluginListFile {
    /// Reads the file as MO2's game plugins do (`CreationGamePlugins::readPluginList`):
    /// lines are trimmed, `#` lines and blank lines skipped, `*` means active.
    pub fn parse(data: &[u8]) -> Self {
        let mut plugins = Vec::new();
        for line in data.split(|b| *b == b'\n') {
            let line = line.trim_ascii();
            if line.is_empty() || line[0] == b'#' {
                continue;
            }
            let (active, name) = match line.strip_prefix(b"*") {
                Some(rest) => (true, rest),
                None => (false, line),
            };
            if !name.is_empty() {
                plugins.push((String::from_utf8_lossy(name).into_owned(), active));
            }
        }
        Self { plugins }
    }

    /// Writes the file as MO2 does (`CreationGamePlugins::writePluginList`): the header,
    /// then one line per plugin, `*` before active ones, CRLF line ends.
    pub fn to_bytes(&self) -> Vec<u8> {
        let mut out = format!("{MODLIST_HEADER}\r\n").into_bytes();
        for (name, active) in &self.plugins {
            if *active {
                out.push(b'*');
            }
            out.extend_from_slice(name.as_bytes());
            out.extend_from_slice(b"\r\n");
        }
        out
    }
}

#[cfg(test)]
mod plugin_tests {
    use super::*;

    #[test]
    fn plugin_lists_round_trip() {
        let file: &[u8] = b"# This file was automatically generated by Mod Organizer.\r\n*a.esm\r\nb.esp\r\n*c d.esl\r\n";
        let list = PluginListFile::parse(file);
        assert_eq!(list.plugins, [("a.esm".into(), true), ("b.esp".into(), false), ("c d.esl".into(), true)]);
        assert_eq!(list.to_bytes(), file);
    }
}
