//! The Saves tab's rules on an instance built on disk: the saves folder and missing plugins.

use std::fs;
use std::path::Path;

use strata_core::Instance;
use strata_core::plugins::{AvailablePlugin, MissingPlugin};
use strata_game::SaveGame;
use strata_game::plugin::{FLAG_MASTER, build_plugin};

fn write(path: &Path, data: &[u8]) {
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, data).unwrap();
}

fn build(root: &Path, settings: &str) {
    let game = root.join("Game Root");
    let wine_game = format!("Z:{}", game.to_string_lossy().replace('/', "\\\\"));
    let prefix = root.join("Prefix");
    write(
        &root.join("ModOrganizer.ini"),
        format!(
            "[General]\ngameName=Skyrim Special Edition\nselected_profile=@ByteArray(Default)\n\
             gamePath=@ByteArray({wine_game})\n[fluorine]\nprefix_path={}\n",
            prefix.display()
        )
        .as_bytes(),
    );
    write(&game.join("Data/Skyrim.esm"), &build_plugin(FLAG_MASTER, 44, &[], "", 1));
    write(&root.join("mods/Has/x.esp"), &build_plugin(0, 44, &[], "", 1));
    write(&root.join("mods/Also/X.ESP"), &build_plugin(0, 44, &[], "", 1));
    write(&root.join("overwrite/y.esl"), b"");
    write(
        &root.join("profiles/Default/modlist.txt"),
        b"# This file was automatically generated by Mod Organizer.\r\n-Has\r\n-Also\r\n",
    );
    write(&root.join("profiles/Default/settings.ini"), settings.as_bytes());
}

#[test]
fn missing_plugins_name_the_mods_that_have_them() {
    let tmp = tempfile::tempdir().unwrap();
    build(tmp.path(), "[General]\nLocalSaves=true\n");
    let instance = Instance::open(tmp.path()).unwrap();
    let profile = instance.profile(None).unwrap();
    let skyrim = tmp.path().join("Game Root/Data/Skyrim.esm");
    let available = vec![AvailablePlugin { name: "Skyrim.esm".into(), origin: "<game>".into(), path: skyrim }];
    let list = instance.plugin_list(&profile, available).unwrap();
    let save = SaveGame {
        plugins: vec!["Skyrim.esm".into(), "x.esp".into(), "gone.esp".into()],
        light_plugins: vec!["y.esl".into()],
        ..SaveGame::default()
    };
    let missing = instance.missing_plugins(&profile, &list, &save).unwrap();
    assert_eq!(
        missing,
        [
            MissingPlugin { name: "x.esp".into(), providers: vec!["Also".into(), "Has".into()] },
            MissingPlugin { name: "gone.esp".into(), providers: vec![] },
            MissingPlugin { name: "y.esl".into(), providers: vec!["<overwrite>".into()] },
        ]
    );
}

#[test]
fn the_saves_folder_follows_local_saves_and_the_ini() {
    let tmp = tempfile::tempdir().unwrap();
    build(tmp.path(), "[General]\nLocalSaves=true\n");
    let instance = Instance::open(tmp.path()).unwrap();
    let profile = instance.profile(None).unwrap();
    assert_eq!(instance.saves_dir(&profile).unwrap(), profile.dir.join("saves"));

    let tmp = tempfile::tempdir().unwrap();
    build(tmp.path(), "[General]\nLocalSaves=false\nLocalSettings=true\n");
    write(&tmp.path().join("profiles/Default/skyrim.ini"), b"[General]\r\nSLocalSavePath=MySaves\\\r\n");
    let instance = Instance::open(tmp.path()).unwrap();
    let profile = instance.profile(None).unwrap();
    let documents = tmp.path().join("Prefix/pfx/drive_c/users/steamuser/Documents/My Games/Skyrim Special Edition");
    assert_eq!(instance.saves_dir(&profile).unwrap(), documents.join("MySaves"));

    fs::remove_file(tmp.path().join("profiles/Default/skyrim.ini")).unwrap();
    assert_eq!(instance.saves_dir(&profile).unwrap(), documents.join("Saves"));
    assert!(instance.saves(&profile, false).unwrap().is_empty(), "a missing folder is no saves, not an error");
}
