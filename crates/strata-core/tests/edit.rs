//! Writing operations on an instance built on disk: mods, separators, profiles, overwrite.

use std::fs;
use std::path::Path;

use strata_core::separators::DropTarget;
use strata_core::write::Transaction;
use strata_core::{Error, Instance, ModKind, ModList, ModListEvent, Trash};

fn write(path: &Path, text: &str) {
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, text).unwrap();
}

const HEADER: &str = "# This file was automatically generated by Mod Organizer.\r\n";

/// Mods A, B, C under a separator S, a second profile "Other", a prefix with inis.
fn build(root: &Path) {
    let game = root.join("Game Root");
    let wine_game = format!("Z:{}", game.to_string_lossy().replace('/', "\\\\"));
    write(
        &root.join("ModOrganizer.ini"),
        &format!(
            "[General]\ngameName=Skyrim Special Edition\nselected_profile=@ByteArray(Default)\n\
             gamePath=@ByteArray({wine_game})\n[Settings]\ndisplay_foreign=false\n[fluorine]\nprefix_path={}\n",
            root.join("Prefix").display()
        ),
    );
    write(&game.join("Data/Skyrim.esm"), "");
    write(&game.join("Skyrim_default.ini"), "default");
    let user = root.join("Prefix/pfx/drive_c/users/steamuser");
    write(&user.join("Documents/My Games/Skyrim Special Edition/Skyrim.ini"), "mine");
    write(&user.join("Documents/My Games/Skyrim Special Edition/SkyrimPrefs.ini"), "prefs");
    write(&user.join("AppData/Local/Skyrim Special Edition/plugins.txt"), "*a.esp\n");
    for name in ["A", "B", "C", "S_separator"] {
        write(&root.join("mods").join(name).join("meta.ini"), "[General]\nmodid=0\n");
    }
    write(&root.join("overwrite/SKSE/Plugins/x.log"), "log");
    let list = format!("{HEADER}+C\r\n-B\r\n+S_separator\r\n+A\r\n");
    write(&root.join("profiles/Default/modlist.txt"), &list);
    write(&root.join("profiles/Default/settings.ini"), "[General]\r\nLocalSaves=false\r\nLocalSettings=true\r\n");
    write(&root.join("profiles/Other/modlist.txt"), &format!("{HEADER}-A\r\n+C\r\n"));
}

fn names(list: &ModList) -> Vec<&str> {
    list.entries().iter().map(|e| e.name.as_str()).collect()
}

#[test]
fn enable_move_and_save_write_what_mo2_reads() {
    let tmp = tempfile::tempdir().unwrap();
    build(tmp.path());
    let instance = Instance::open(tmp.path()).unwrap();
    let profile = instance.profile(None).unwrap();
    let mut list = ModList::load(&instance, &profile).unwrap();
    assert_eq!(names(&list), ["A", "S_separator", "B", "C"]);
    list.set_enabled(&["B"], true).unwrap();
    list.set_priority("A", 3).unwrap();
    assert!(list.save().unwrap());
    assert!(!list.save().unwrap(), "nothing changed: not written again");
    let text = fs::read_to_string(tmp.path().join("profiles/Default/modlist.txt")).unwrap();
    assert_eq!(text, format!("{HEADER}+A\r\n+C\r\n+B\r\n+S_separator\r\n"));
    let again = ModList::load(&instance, &instance.profile(None).unwrap()).unwrap();
    assert_eq!(again.entries(), list.entries());
}

#[test]
fn create_rename_and_drop_mods_and_separators() {
    let tmp = tempfile::tempdir().unwrap();
    build(tmp.path());
    let instance = Instance::open(tmp.path()).unwrap();
    let mods = &instance.paths.mods;
    let mut list = ModList::load(&instance, &instance.profile(None).unwrap()).unwrap();

    // a mod "at" C goes just below it in priority; a mod at the separator goes to its end
    list.create_mod(mods, "  New:  mod ", Some("C")).unwrap();
    assert_eq!(names(&list), ["A", "S_separator", "B", "New mod", "C"]);
    assert_eq!(fs::read(mods.join("New mod/meta.ini")).unwrap(), strata_core::new_mod_meta());
    assert!(matches!(list.create_mod(mods, "new MOD", None), Err(Error::Exists { .. })));

    // a separator inside S: at S's end, level 1
    list.create_separator(mods, "Inner", Some("S_separator")).unwrap();
    assert_eq!(names(&list), ["A", "S_separator", "B", "New mod", "C", "Inner_separator"]);
    assert_eq!(list.get("Inner_separator").unwrap().nest, 1);
    let tree = list.tree();
    assert_eq!(tree.children[1], [2, 3, 4, 5]);

    // drop A onto Inner: A goes to Inner's end (the end of the list)
    let plan = tree.plan_drop(list.entries(), DropTarget { parent: Some(5), row: None, below_expanded_separator: false }, &[0]).unwrap();
    let mut txn = Transaction::new(&instance.strata_dir()).unwrap();
    list.apply_drop(&plan, &[0], &mut txn).unwrap();
    list.stage(&mut txn).unwrap();
    txn.commit().unwrap();
    assert_eq!(names(&list), ["S_separator", "B", "New mod", "C", "Inner_separator", "A"]);

    // drop Inner (with A) to the top level, first row: level 0
    let tree = list.tree();
    let plan = tree.plan_drop(list.entries(), DropTarget { parent: None, row: Some(0), below_expanded_separator: false }, &[4, 5]).unwrap();
    let mut txn = Transaction::new(&instance.strata_dir()).unwrap();
    let events = list.apply_drop(&plan, &[4, 5], &mut txn).unwrap();
    list.stage(&mut txn).unwrap();
    txn.commit().unwrap();
    assert!(events.contains(&ModListEvent::NestChanged { name: "Inner_separator".into(), nest: 0 }));
    assert_eq!(names(&list), ["Inner_separator", "A", "S_separator", "B", "New mod", "C"]);
    let reread = ModList::load(&instance, &instance.profile(None).unwrap()).unwrap();
    assert_eq!(reread.entries(), list.entries(), "the files say what the list says (levels included)");

    // rename C: the folder and both profiles' lists
    list.rename_mod(&instance, "C", "Cee").unwrap();
    assert!(mods.join("Cee").is_dir() && !mods.join("C").exists());
    let other = fs::read_to_string(tmp.path().join("profiles/Other/modlist.txt")).unwrap();
    assert_eq!(other, format!("{HEADER}-A\r\n+Cee\r\n"));
    // a separator keeps its suffix
    list.rename_mod(&instance, "Inner_separator", "Outer").unwrap();
    assert!(mods.join("Outer_separator").is_dir());
    assert!(matches!(list.rename_mod(&instance, "A", "b"), Err(Error::Exists { .. })));
    assert!(!instance.strata_dir().join("journal").exists());
}

#[test]
fn profiles_are_created_copied_renamed_and_deleted() {
    let tmp = tempfile::tempdir().unwrap();
    build(tmp.path());
    let instance = Instance::open(tmp.path()).unwrap();
    let profiles = &instance.paths.profiles;

    let (fresh, _) = instance.create_profile(" Fresh ", false).unwrap();
    assert_eq!(fresh.name, "Fresh");
    let read = |p: &str| fs::read_to_string(profiles.join(p)).unwrap();
    assert_eq!(read("Fresh/modlist.txt"), "");
    assert_eq!(read("Fresh/plugins.txt"), "*a.esp\n", "from the prefix");
    assert_eq!(read("Fresh/Skyrim.ini"), "mine");
    assert_eq!(read("Fresh/SkyrimPrefs.ini"), "prefs");
    assert_eq!(read("Fresh/SkyrimCustom.ini"), "", "missing in the prefix: created empty");
    assert_eq!(read("Fresh/settings.ini"), "[General]\nLocalSaves=false\nLocalSettings=true\nAutomaticArchiveInvalidation=true\n");
    assert!(fresh.local_settings && !fresh.local_saves);
    let (defaults, _) = instance.create_profile("Defaults", true).unwrap();
    assert_eq!(read("Defaults/Skyrim.ini"), "default", "prefer defaults: the game's default ini");
    assert!(defaults.dir.is_dir());
    assert!(matches!(instance.create_profile("fresh", false), Err(Error::Exists { .. })));

    write(&profiles.join("Default/saves/a.ess"), "save");
    instance.copy_profile("Default", "Copy").unwrap();
    assert_eq!(read("Copy/saves/a.ess"), "save");
    assert_eq!(read("Copy/modlist.txt"), read("Default/modlist.txt"));
    assert_eq!(read("Copy/plugins.txt"), "*a.esp\n");

    assert!(matches!(instance.rename_profile("Default", "X"), Err(Error::ActiveProfile { .. })));
    // selecting rewrites one line of ModOrganizer.ini
    let before = fs::read_to_string(tmp.path().join("ModOrganizer.ini")).unwrap();
    let mut chooser = Instance::open(tmp.path()).unwrap();
    chooser.select_profile("fresh").unwrap();
    let after = fs::read_to_string(tmp.path().join("ModOrganizer.ini")).unwrap();
    assert_eq!(after, before.replace("@ByteArray(Default)", "@ByteArray(Fresh)"));
    assert_eq!(Instance::open(tmp.path()).unwrap().selected_profile, "Fresh");
    chooser.select_profile("Default").unwrap();
    assert_eq!(fs::read_to_string(tmp.path().join("ModOrganizer.ini")).unwrap(), before);
    instance.rename_profile("Copy", "Copied").unwrap();
    assert!(profiles.join("Copied").is_dir() && !profiles.join("Copy").exists());

    let trash = Trash::at(tmp.path().join("Trash"));
    assert!(matches!(instance.delete_profile("Default", Some(&trash)), Err(Error::ActiveProfile { .. })));
    instance.delete_profile("Copied", Some(&trash)).unwrap();
    assert!(!profiles.join("Copied").exists());
    assert!(tmp.path().join("Trash/files/Copied/saves/a.ess").exists());
    assert_eq!(instance.profile_names().unwrap(), ["Default", "Defaults", "Fresh", "Other"]);
}

#[test]
fn local_saves_and_inis_switch() {
    let tmp = tempfile::tempdir().unwrap();
    build(tmp.path());
    let instance = Instance::open(tmp.path()).unwrap();
    let trash = Trash::at(tmp.path().join("Trash"));
    let profile = instance.profile(Some("Other")).unwrap();
    assert!(!profile.local_saves && !profile.local_settings);

    instance.set_local_saves(&profile, true, false, None).unwrap();
    instance.set_local_settings(&profile, true, false, None).unwrap();
    let profile = instance.profile(Some("Other")).unwrap();
    assert!(profile.local_saves && profile.local_settings);
    assert!(profile.dir.join("saves").is_dir());
    assert_eq!(fs::read_to_string(profile.dir.join("Skyrim.ini")).unwrap(), "mine");

    // off, keeping the files; then off again, deleting them
    instance.set_local_settings(&profile, false, false, None).unwrap();
    assert!(profile.dir.join("Skyrim.ini").exists());
    instance.set_local_settings(&profile, false, true, Some(&trash)).unwrap();
    assert!(!profile.dir.join("Skyrim.ini").exists());
    instance.set_local_saves(&profile, false, true, Some(&trash)).unwrap();
    assert!(!profile.dir.join("saves").exists());
    let profile = instance.profile(Some("Other")).unwrap();
    assert!(!profile.local_saves && !profile.local_settings);
    assert_eq!(fs::read_to_string(profile.dir.join("settings.ini")).unwrap(), "[General]\nLocalSaves=false\nLocalSettings=false\n");
}

#[test]
fn overwrite_is_cleared_or_moved_into_a_mod() {
    let tmp = tempfile::tempdir().unwrap();
    build(tmp.path());
    let instance = Instance::open(tmp.path()).unwrap();
    let mut list = ModList::load(&instance, &instance.profile(None).unwrap()).unwrap();
    assert!(!instance.overwrite_is_empty());
    list.create_mod(&instance.paths.mods, "From Overwrite", None).unwrap();
    instance.move_overwrite_to(&instance.paths.mods.join("From Overwrite")).unwrap();
    assert!(instance.overwrite_is_empty());
    assert!(instance.paths.mods.join("From Overwrite/SKSE/Plugins/x.log").exists());
    assert_eq!(list.get("From Overwrite").unwrap().kind, ModKind::Regular);

    write(&tmp.path().join("overwrite/again.txt"), "x");
    write(&instance.strata_dir().join("whiteouts.txt"), "Data/gone.esp\n");
    let trash = Trash::at(tmp.path().join("Trash"));
    instance.clear_overwrite(Some(&trash)).unwrap();
    assert!(instance.overwrite_is_empty());
    assert!(tmp.path().join("Trash/files/again.txt").exists());
    assert!(!instance.strata_dir().join("whiteouts.txt").exists());
}

#[test]
fn mods_are_removed_to_the_trash_or_for_good() {
    let tmp = tempfile::tempdir().unwrap();
    build(tmp.path());
    let mut instance = Instance::open(tmp.path()).unwrap();
    let mut list = ModList::load(&instance, &instance.profile(None).unwrap()).unwrap();
    let trash = Trash::at(tmp.path().join("Trash"));
    let events = list.remove_mods(&["b"], Some(&trash)).unwrap();
    assert_eq!(events, [ModListEvent::Removed { name: "B".into(), priority: 2 }]);
    assert!(tmp.path().join("Trash/files/B/meta.ini").exists());
    list.remove_mods(&["A"], None).unwrap();
    assert!(!tmp.path().join("mods/A").exists() && !tmp.path().join("Trash/files/A").exists());
    assert_eq!(names(&list), ["S_separator", "C"]);
    assert!(list.entries().iter().enumerate().all(|(i, e)| e.priority == i));
    list.save().unwrap();
    let text = fs::read_to_string(tmp.path().join("profiles/Default/modlist.txt")).unwrap();
    assert_eq!(text, format!("{HEADER}+C\r\n+S_separator\r\n"));

    // the remembered answer of the confirmation (Leet change 8)
    use strata_core::DeleteChoice;
    assert_eq!(instance.delete_choice("removeMod"), None);
    instance.set_delete_choice("removeMod", Some(DeleteChoice::Trash)).unwrap();
    assert!(fs::read_to_string(tmp.path().join("ModOrganizer.ini")).unwrap().contains("[DialogChoices]\nremoveMod=16384\n"));
    assert_eq!(Instance::open(tmp.path()).unwrap().delete_choice("removeMod"), Some(DeleteChoice::Trash));
    instance.set_delete_choice("removeMods", Some(DeleteChoice::Permanent)).unwrap();
    assert_eq!(instance.delete_choice("removeMods"), Some(DeleteChoice::Permanent));
    instance.reset_dialog_choices().unwrap();
    assert_eq!(Instance::open(tmp.path()).unwrap().delete_choice("removeMods"), None);
}

#[test]
fn executables_are_stored_as_mo2_stores_them() {
    use strata_core::Executable;
    let tmp = tempfile::tempdir().unwrap();
    build(tmp.path());
    let mut instance = Instance::open(tmp.path()).unwrap();
    let skse = Executable { title: "SKSE".into(), binary: "Z:\\g\\skse64_loader.exe".into(), toolbar: true, ..Default::default() };
    let xedit = Executable { title: "xEdit".into(), binary: "/t/SSEEdit.exe".into(), arguments: "-quickautoclean".into(), ..Default::default() };
    assert!(instance.store_executables(&[skse.clone(), xedit.clone()]).unwrap());
    assert!(!instance.store_executables(&[skse.clone(), xedit.clone()]).unwrap(), "the same list: not written");
    let ini = fs::read_to_string(tmp.path().join("ModOrganizer.ini")).unwrap();
    assert!(ini.contains("[customExecutables]\nsize=2\n1\\arguments=\n1\\binary=Z:\\\\g\\\\skse64_loader.exe\n1\\hide=false\n1\\ownicon=false\n1\\steamAppID=\n1\\title=SKSE\n1\\toolbar=true\n1\\workingDirectory=\n2\\arguments=-quickautoclean\n"), "{ini}");
    assert_eq!(Instance::open(tmp.path()).unwrap().executables(), [skse.clone(), xedit.clone()]);
    // reorder, then remove one: the section is rebuilt
    instance.store_executables(&[xedit.clone(), skse.clone()]).unwrap();
    assert_eq!(Instance::open(tmp.path()).unwrap().executables(), [xedit.clone(), skse.clone()]);
    instance.store_executables(std::slice::from_ref(&skse)).unwrap();
    let ini = fs::read_to_string(tmp.path().join("ModOrganizer.ini")).unwrap();
    assert!(!ini.contains("2\\title"), "{ini}");
    assert_eq!(Instance::open(tmp.path()).unwrap().executables(), [skse]);

    // a binary in a mod's Root folder runs from the game folder
    let root_exe = format!("{}/SKSE/Root/skse64_loader.exe", instance.paths.mods.display());
    assert_eq!(instance.root_path_in_game(&root_exe).unwrap(), format!("{}/skse64_loader.exe", instance.game_path.display()));
    let wine = strata_core::winepath::to_wine(&instance.paths.mods.join("SKSE/root/sub/x.exe"));
    assert_eq!(instance.root_path_in_game(&wine).unwrap(), strata_core::winepath::to_wine(&instance.game_path.join("sub/x.exe")));
    assert_eq!(instance.root_path_in_game("Z:\\elsewhere\\x.exe"), None);
}

#[test]
fn the_ini_editor_finds_and_saves_the_profiles_inis() {
    use std::os::unix::fs::PermissionsExt;
    use strata_core::inis::ReadOnly;
    let tmp = tempfile::tempdir().unwrap();
    build(tmp.path());
    let instance = Instance::open(tmp.path()).unwrap();
    // Default has local settings: its inis are in the profile (matched without case).
    let default = instance.profile(Some("Default")).unwrap();
    write(&default.dir.join("skyrim.ini"), "[General]\r\nsLanguage=ENGLISH\r\n");
    let files = instance.ini_files(&default);
    let names: Vec<_> = files.iter().map(|f| f.name.as_str()).collect();
    assert_eq!(names, ["Skyrim.ini", "SkyrimPrefs.ini", "SkyrimCustom.ini"]);
    assert_eq!(files[0].path.as_deref(), Some(default.dir.join("skyrim.ini").as_path()));
    assert!(files[0].editable() && !files[2].editable());

    // Saved with CRLF; the same text again writes nothing.
    assert!(instance.save_ini(&default, "Skyrim.ini", "[General]\nsLanguage=GERMAN\n", ReadOnly::Refuse).unwrap());
    assert_eq!(fs::read(default.dir.join("skyrim.ini")).unwrap(), b"[General]\r\nsLanguage=GERMAN\r\n");
    assert!(!instance.save_ini(&default, "Skyrim.ini", "[General]\nsLanguage=GERMAN\n", ReadOnly::Refuse).unwrap());
    assert!(instance.save_ini(&default, "Other.ini", "", ReadOnly::Refuse).is_err());

    // Other has no local settings: the prefix's file; read-only is refused, "once" keeps it read-only.
    let other = instance.profile(Some("Other")).unwrap();
    let prefix_ini = tmp.path().join("Prefix/pfx/drive_c/users/steamuser/Documents/My Games/Skyrim Special Edition/Skyrim.ini");
    assert_eq!(instance.ini_files(&other)[0].path.as_deref(), Some(prefix_ini.as_path()));
    fs::set_permissions(&prefix_ini, fs::Permissions::from_mode(0o444)).unwrap();
    assert!(instance.ini_files(&other)[0].read_only);
    assert!(instance.save_ini(&other, "Skyrim.ini", "x", ReadOnly::Refuse).is_err());
    assert_eq!(fs::read_to_string(&prefix_ini).unwrap(), "mine");
    instance.save_ini(&other, "Skyrim.ini", "once", ReadOnly::Once).unwrap();
    assert_eq!(fs::read_to_string(&prefix_ini).unwrap(), "once");
    assert_eq!(fs::metadata(&prefix_ini).unwrap().permissions().mode() & 0o777, 0o444);
    instance.save_ini(&other, "Skyrim.ini", "clear", ReadOnly::Clear).unwrap();
    assert_eq!(fs::metadata(&prefix_ini).unwrap().permissions().mode() & 0o777, 0o644);
}

