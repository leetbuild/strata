//! Opening an instance built on disk: paths, profile, mod order, layers.

use std::fs;
use std::path::Path;

use strata_core::{Error, Instance, ModKind, resolve_layers};
use strata_game::LayerKind;

fn write(path: &Path, text: &str) {
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, text).unwrap();
}

/// A small instance: three mods, a separator, a backup, a folder the list doesn't know.
fn build(root: &Path) {
    let game = root.join("Game Root");
    let wine_game = format!("Z:{}", game.to_string_lossy().replace('/', "\\\\"));
    write(
        &root.join("ModOrganizer.ini"),
        &format!(
            "[General]\ngameName=Skyrim Special Edition\nselected_profile=@ByteArray(Default)\n\
             gamePath=@ByteArray({wine_game})\n[customExecutables]\nsize=2\n1\\title=SKSE\n\
             1\\binary={wine_game}\\\\skse64_loader.exe\n1\\arguments=\n2\\title=xEdit\n\
             2\\binary=C:\\\\tools\\\\SSEEdit.exe\n2\\arguments=-D:\\\"{wine_game}\\\\Data\\\" -quick\n[fluorine]\nprefix_path=/somewhere/Prefix\nsteam_drm=true\n"
        ),
    );
    write(&game.join("Data/Skyrim.esm"), "");
    // foreign mods: game plugins that are not primary plugins
    write(&game.join("Data/Extra.esp"), "");
    write(&game.join("Data/Listed.esm"), "");
    write(&game.join("Data/_ResourcePack.esl"), "");
    write(&game.join("Skyrim.ccc"), "ccBGSSSE001-Fish.esm\r\nUpdate.esm\r\n\r\nccbgssse001-fish.esm\r\n_ResourcePack.esl\r\n");
    for name in ["Alpha", "beta", "Gamma", "Tools_separator", "Alpha backup2", "Unlisted"] {
        write(&root.join("mods").join(name).join("meta.ini"), "[General]\n");
    }
    fs::create_dir_all(root.join("overwrite")).unwrap();
    write(
        &root.join("profiles/Default/modlist.txt"),
        "# This file was automatically generated by Mod Organizer.\r\n*Unmanaged: Listed\r\n+Gamma\r\n-Beta\r\n+Tools_separator\r\n\
         +Gone\r\n+Alpha\r\n*DLC: Dawnguard\r\n",
    );
    write(&root.join("profiles/Default/settings.ini"), "[General]\nLocalSaves=true\nLocalSettings=false\n");
}

#[test]
fn opens_an_instance_and_orders_its_mods() {
    let tmp = tempfile::tempdir().unwrap();
    build(tmp.path());
    let instance = Instance::open(tmp.path()).unwrap();

    assert_eq!(instance.game.name(), "Skyrim Special Edition");
    assert_eq!(instance.game_path, tmp.path().join("Game Root"));
    assert_eq!(instance.paths.mods, tmp.path().join("mods"));
    assert_eq!(instance.proton.prefix.as_deref(), Some(Path::new("/somewhere/Prefix")));
    assert!(instance.proton.steam_drm);
    assert_eq!(instance.profile_names().unwrap(), ["Default"]);

    assert_eq!(
        instance.primary_plugins(),
        ["skyrim.esm", "update.esm", "dawnguard.esm", "hearthfires.esm", "dragonborn.esm", "ccBGSSSE001-Fish.esm", "_ResourcePack.esl"]
    );
    let exes = instance.executables();
    assert_eq!(exes.len(), 2);
    assert_eq!(exes[0].title, "SKSE");
    assert!(exes[0].binary.ends_with("Game Root\\skse64_loader.exe"), "{}", exes[0].binary);
    assert!(exes[1].arguments.starts_with("-D:\"Z:") && exes[1].arguments.ends_with("\\Data\" -quick"), "{}", exes[1].arguments);

    let profile = instance.profile(None).unwrap();
    assert!(profile.local_saves && !profile.local_settings);

    let mods = instance.mod_list(&profile).unwrap();
    let seen: Vec<_> = mods.iter().map(|m| (m.name.as_str(), m.kind, m.enabled, m.listed)).collect();
    assert_eq!(
        seen,
        [
            // foreign mods the list doesn't name go to the bottom
            ("Unmanaged: Extra", ModKind::Foreign, true, false),
            // bottom line of modlist.txt = lowest priority; "DLC: Dawnguard" is no mod
            // (Dawnguard.esm is a primary plugin), so it is dropped
            ("Alpha", ModKind::Regular, true, true),
            ("Tools_separator", ModKind::Separator, true, true),
            // listed as "Beta", the folder is "beta": names compare without case
            ("beta", ModKind::Regular, false, true),
            ("Gamma", ModKind::Regular, true, true),
            ("Unmanaged: Listed", ModKind::Foreign, true, true),
            // not in the list: on top, disabled; then backups
            ("Unlisted", ModKind::Regular, false, false),
            ("Alpha backup2", ModKind::Backup, false, false),
        ]
    );
    assert!(mods.iter().enumerate().all(|(i, m)| m.priority == i));

    let layers = resolve_layers(&instance, &profile).unwrap();
    let ids: Vec<_> = layers.iter().map(|l| (l.id.as_str(), l.kind)).collect();
    assert_eq!(
        ids,
        [
            ("<game>", LayerKind::Game),
            ("Alpha", LayerKind::Mod),
            ("Gamma", LayerKind::Mod),
            ("<overwrite>", LayerKind::Overwrite)
        ]
    );
}

#[test]
fn errors_say_what_is_wrong() {
    let tmp = tempfile::tempdir().unwrap();
    assert!(matches!(Instance::open(tmp.path()), Err(Error::NotAnInstance { .. })));
    build(tmp.path());
    let instance = Instance::open(tmp.path()).unwrap();
    let message = instance.profile(Some("Nope")).unwrap_err().to_string();
    assert!(message.contains("Nope") && message.contains("Default"), "{message}");
}
